-- ============================================================================
-- 7. Permisos de Esquema/Tablas + Row Level Security (RLS)
-- ============================================================================

GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON public.categorias, public.productos, public.media TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.categorias, public.productos, public.media TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.media ENABLE ROW LEVEL SECURITY;

-- Políticas para categorias
DROP POLICY IF EXISTS "Lectura pública de categorias" ON public.categorias;
CREATE POLICY "Lectura pública de categorias"
  ON public.categorias
  FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Inserción autenticada de categorias" ON public.categorias;
CREATE POLICY "Inserción autenticada de categorias"
  ON public.categorias
  FOR INSERT
  WITH CHECK (auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Actualización autenticada de categorias" ON public.categorias;
CREATE POLICY "Actualización autenticada de categorias"
  ON public.categorias
  FOR UPDATE
  USING (auth.role() = 'authenticated')
  WITH CHECK (auth.role() = 'authenticated');

