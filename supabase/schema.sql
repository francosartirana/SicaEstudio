-- 1. Tipo enumerado para multimedia
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'tipo_media') THEN
    CREATE TYPE public.tipo_media AS ENUM ('IMAGEN', 'VIDEO');
  END IF;
END
$$;

-- 2. Tabla: categorias
CREATE TABLE IF NOT EXISTS public.categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  slug TEXT NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabla: productos
CREATE TABLE IF NOT EXISTS public.productos (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre TEXT NOT NULL,
  descripcion TEXT,
  categoria_id BIGINT NOT NULL REFERENCES public.categorias(id) ON DELETE RESTRICT,
  mostrar_en_espiral BOOLEAN NOT NULL DEFAULT false,
  mostrar_en_galeria BOOLEAN NOT NULL DEFAULT false,
  mostrar_en_seccion BOOLEAN NOT NULL DEFAULT false,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Columnas adicionales idempotentes si la tabla ya existía
ALTER TABLE public.productos
  ADD COLUMN IF NOT EXISTS mostrar_en_espiral BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE public.productos
  ADD COLUMN IF NOT EXISTS mostrar_en_galeria BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE public.productos
  ADD COLUMN IF NOT EXISTS mostrar_en_seccion BOOLEAN NOT NULL DEFAULT false;

-- 4. Tabla: media
CREATE TABLE IF NOT EXISTS public.media (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  producto_id UUID NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  url TEXT NOT NULL,
  storage_path TEXT,
  tipo public.tipo_media NOT NULL,
  rol TEXT NOT NULL DEFAULT 'GALERIA' CHECK (rol IN ('PRESENTACION', 'GALERIA')),
  orden INT NOT NULL DEFAULT 0,
  alt_text TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.media
  ADD COLUMN IF NOT EXISTS rol TEXT NOT NULL DEFAULT 'GALERIA';

-- 5. Índices para optimizar consultas de catálogo y galería
CREATE INDEX IF NOT EXISTS idx_productos_categoria_id
  ON public.productos (categoria_id);

CREATE INDEX IF NOT EXISTS idx_media_producto_orden
  ON public.media (producto_id, orden);

