-- Políticas RLS sobre storage.objects para el bucket 'portfolio'
DROP POLICY IF EXISTS "Lectura pública de portfolio" ON storage.objects;
CREATE POLICY "Lectura pública de portfolio"
  ON storage.objects
  FOR SELECT
  USING (bucket_id = 'portfolio');

DROP POLICY IF EXISTS "Subida autenticada en portfolio" ON storage.objects;
CREATE POLICY "Subida autenticada en portfolio"
  ON storage.objects
  FOR INSERT
  WITH CHECK (bucket_id = 'portfolio' AND auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Actualización autenticada en portfolio" ON storage.objects;
CREATE POLICY "Actualización autenticada en portfolio"
  ON storage.objects
  FOR UPDATE
  USING (bucket_id = 'portfolio' AND auth.role() = 'authenticated')
  WITH CHECK (bucket_id = 'portfolio' AND auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Eliminación autenticada en portfolio" ON storage.objects;
CREATE POLICY "Eliminación autenticada en portfolio"
  ON storage.objects
  FOR DELETE
  USING (bucket_id = 'portfolio' AND auth.role() = 'authenticated');
